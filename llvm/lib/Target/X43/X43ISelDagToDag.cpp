#define DEBUG_TYPE "X43-isel"

namespace {

class X43DAGToDAGISel : public SelectionDAGISel {

public:
  static char ID;
  X43DAGToDAGISel() = delete;
  explicit X43DAGToDAGISel(X43TargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {}

  bool runOnMachineFunction(MachineFunction &MF) override {
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  void Select(SDNode *N) override;

// Include the pieces autogenerated from the target description.
#include "X43GenDAGISel.inc"
};
class X43DAGToDAGISelLegacy : public SelectionDAGISelLegacy {
public:
  static char ID;

  X43DAGToDAGISelLegacy(X43TargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISelLegacy(
            ID, std::make_unique<X43DAGToDAGISel>(TM, OptLevel)) {}

  StringRef getPassName() const override {
    return "X43 DAG->DAG Pattern Instruction Selection";
  }
};
} // end anonymous namespace

char X43DAGToDAGISelLegacy::ID = 0;

/// This pass converts a legalized DAG into a X43-specific DAG, ready for
/// instruction scheduling.
FunctionPass *llvm::createX43ISelDag(X43TargetMachine &TM,
                                     CodeGenOptLevel OptLevel) {
  return new X43DAGToDAGISelLegacy(TM, OptLevel);
}

void X43DAGToDAGISel::Select(SDNode *Node) {
  if (Node->isMachineOpcode()) {
    Node->setNodeId(-1);
    return;
  }
  SDLoc DL(Node);
  SelectCode(Node);
}